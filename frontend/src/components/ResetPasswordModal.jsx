import React, { useState, useEffect } from 'react';
import useModalEscape from '../hooks/useModalEscape';
import { FormField } from './ui/forms';

export default function ResetPasswordModal({ isOpen, user, onClose, onSubmit }) {
  const [mode, setMode] = useState('auto'); // 'auto' | 'manual'
  const [password, setPassword] = useState('');
  const [showPassword, setShowPassword] = useState(false);
  const [error, setError] = useState('');
  const [submitting, setSubmitting] = useState(false);
  const [result, setResult] = useState(null);
  const [copied, setCopied] = useState(false);

  useModalEscape(isOpen, onClose);

  useEffect(() => {
    if (!isOpen) return;
    setMode('auto');
    setPassword('');
    setShowPassword(false);
    setError('');
    setSubmitting(false);
    setResult(null);
    setCopied(false);
  }, [isOpen, user]);

  if (!isOpen || !user) return null;

  const handleSubmit = async (e) => {
    e.preventDefault();
    setError('');

    if (mode === 'manual') {
      if (!password || password.length < 8) {
        setError('Le mot de passe doit comporter au moins 8 caractères (règle SEC-07).');
        return;
      }
      if (!/[A-Za-z]/.test(password) || !/[0-9]/.test(password)) {
        setError('Le mot de passe doit contenir au moins une lettre et un chiffre (règle SEC-07).');
        return;
      }
    }

    setSubmitting(true);
    try {
      const payload = mode === 'auto'
        ? { autoGenerate: true }
        : { autoGenerate: false, password };

      const res = await onSubmit({ id: user.id, ...payload });
      const data = res?.data || res || {};
      const finalPassword = data.temporaryPassword || (mode === 'manual' ? password : '');
      setResult({
        username: data.username || user.username,
        password: finalPassword,
        autoGenerated: mode === 'auto'
      });
    } catch (err) {
      setError(err.response?.data?.message || err.message || 'Erreur lors de la réinitialisation du mot de passe.');
    } finally {
      setSubmitting(false);
    }
  };

  const handleCopyCredentials = async () => {
    if (!result) return;
    const text = `Identifiants SYGIM\nIdentifiant : ${result.username}\nNouveau mot de passe : ${result.password}`;
    try {
      await navigator.clipboard.writeText(text);
      setCopied(true);
      setTimeout(() => setCopied(false), 2500);
    } catch (_) {
      // Fallback
    }
  };

  return (
    <div
      className="fixed inset-0 z-[1000] flex items-center justify-center p-4 bg-black/50 backdrop-blur-sm"
      onClick={(e) => { if (e.target === e.currentTarget) onClose(); }}
    >
      <div className="bg-white rounded-2xl shadow-xl w-full max-w-md overflow-hidden flex flex-col">
        {/* Header */}
        <div className="flex items-center justify-between px-6 py-4 border-b border-slate-100">
          <div className="flex items-center gap-3">
            <div className="w-10 h-10 rounded-xl bg-amber-50 text-amber-600 flex items-center justify-center">
              <i className="fas fa-key text-base"></i>
            </div>
            <div>
              <h2 className="text-base font-bold text-slate-900 leading-tight">Réinitialiser le mot de passe</h2>
              <p className="text-xs text-slate-500 font-mono">Compte : {user.username}</p>
            </div>
          </div>
          <button
            type="button"
            onClick={onClose}
            className="w-8 h-8 rounded-lg flex items-center justify-center text-slate-400 hover:text-slate-700 hover:bg-slate-100 transition-colors cursor-pointer"
            aria-label="Fermer"
          >
            <i className="fas fa-times text-sm"></i>
          </button>
        </div>

        {result ? (
          <div className="p-6 space-y-5">
            <div className="p-4 rounded-xl bg-emerald-50 border border-emerald-200 text-emerald-800 space-y-2">
              <div className="flex items-center gap-2 font-bold text-sm">
                <i className="fas fa-check-circle text-emerald-600"></i>
                Mot de passe réinitialisé avec succès !
              </div>
              <p className="text-xs text-emerald-700">
                Les sessions actives de cet utilisateur ont été révoquées. Transmettez-lui ses nouveaux identifiants :
              </p>
            </div>

            <div className="p-4 rounded-xl bg-slate-50 border border-slate-200 space-y-2 font-mono text-xs">
              <div className="flex justify-between items-center">
                <span className="text-slate-500">Identifiant :</span>
                <span className="font-bold text-slate-900 select-all">{result.username}</span>
              </div>
              <div className="flex justify-between items-center">
                <span className="text-slate-500">Mot de passe :</span>
                <span className="font-bold text-primary select-all">{result.password}</span>
              </div>
            </div>

            <div className="flex items-center justify-end gap-3 pt-1">
              <button
                type="button"
                onClick={handleCopyCredentials}
                className={`flex-1 py-2.5 px-4 rounded-xl text-xs font-bold flex items-center justify-center gap-2 transition-all cursor-pointer ${
                  copied
                    ? 'bg-emerald-600 text-white'
                    : 'bg-slate-900 text-white hover:bg-slate-800'
                }`}
              >
                <i className={`fas ${copied ? 'fa-check' : 'fa-copy'}`}></i>
                {copied ? 'Identifiants copiés !' : 'Copier les identifiants'}
              </button>
              <button
                type="button"
                onClick={onClose}
                className="px-4 py-2.5 text-xs font-semibold text-slate-700 bg-white border border-slate-300 rounded-xl hover:bg-slate-50 cursor-pointer"
              >
                Fermer
              </button>
            </div>
          </div>
        ) : (
          <form onSubmit={handleSubmit} className="p-6 space-y-4">
            {error && (
              <div className="flex items-center gap-2 p-3 bg-rose-50 border border-rose-200 rounded-xl text-xs text-rose-700 font-semibold">
                <i className="fas fa-exclamation-circle shrink-0 text-rose-500"></i>
                <span>{error}</span>
              </div>
            )}

            <div className="grid grid-cols-2 gap-2.5">
              <button
                type="button"
                onClick={() => setMode('auto')}
                className={`p-3 rounded-xl border text-left transition-all cursor-pointer ${
                  mode === 'auto'
                    ? 'border-primary bg-primary/5 ring-1 ring-primary'
                    : 'border-slate-200 hover:bg-slate-50'
                }`}
              >
                <div className="text-xs font-bold text-slate-900 flex items-center gap-1.5">
                  <i className="fas fa-magic text-primary"></i> Auto-généré
                </div>
                <p className="text-[11px] text-slate-500 mt-1">Génère un mot de passe temporaire sécurisé.</p>
              </button>

              <button
                type="button"
                onClick={() => setMode('manual')}
                className={`p-3 rounded-xl border text-left transition-all cursor-pointer ${
                  mode === 'manual'
                    ? 'border-primary bg-primary/5 ring-1 ring-primary'
                    : 'border-slate-200 hover:bg-slate-50'
                }`}
              >
                <div className="text-xs font-bold text-slate-900 flex items-center gap-1.5">
                  <i className="fas fa-keyboard text-slate-600"></i> Manuel
                </div>
                <p className="text-[11px] text-slate-500 mt-1">Définir un mot de passe personnalisé.</p>
              </button>
            </div>

            {mode === 'manual' && (
              <FormField
                label="Nouveau mot de passe"
                required
                id="resetPasswordInput"
                hint="Minimum 8 caractères avec lettres et chiffres (SEC-07)"
              >
                <div className="relative">
                  <input
                    id="resetPasswordInput"
                    type={showPassword ? 'text' : 'password'}
                    required
                    value={password}
                    onChange={(e) => setPassword(e.target.value)}
                    placeholder="Ex : Sygim2026!"
                    className="w-full px-4 py-2.5 pr-10 bg-white border border-slate-300 rounded-xl text-sm text-slate-900 focus:outline-none focus:border-primary focus:ring-2 focus:ring-primary/20 transition-all"
                  />
                  <button
                    type="button"
                    onClick={() => setShowPassword(!showPassword)}
                    className="absolute right-3 top-1/2 -translate-y-1/2 text-slate-400 hover:text-slate-600 cursor-pointer"
                  >
                    <i className={`fas ${showPassword ? 'fa-eye-slash' : 'fa-eye'} text-xs`}></i>
                  </button>
                </div>
              </FormField>
            )}

            <div className="flex items-center justify-end gap-3 pt-2 border-t border-slate-100">
              <button
                type="button"
                onClick={onClose}
                disabled={submitting}
                className="px-4 py-2 text-xs font-semibold text-slate-700 bg-white border border-slate-300 rounded-xl hover:bg-slate-50 cursor-pointer"
              >
                Annuler
              </button>
              <button
                type="submit"
                disabled={submitting}
                className="inline-flex items-center gap-2 px-4 py-2 text-xs font-bold text-white bg-amber-600 hover:bg-amber-700 rounded-xl transition-colors shadow-sm disabled:opacity-60 cursor-pointer"
              >
                {submitting
                  ? <><i className="fas fa-spinner fa-spin"></i> Réinitialisation...</>
                  : <><i className="fas fa-key"></i> {mode === 'auto' ? 'Générer automatiquement' : 'Enregistrer le mot de passe'}</>
                }
              </button>
            </div>
          </form>
        )}
      </div>
    </div>
  );
}
